export function normalize(cells) {
 const mx=Math.min(...cells.map(c=>c[0])),my=Math.min(...cells.map(c=>c[1]));
 return cells.map(([x,y])=>[x-mx,y-my]).sort((a,b)=>a[1]-b[1]||a[0]-b[0]);
}
export function orientations(cells) {
 const out=[],seen=new Set();
 for(let flip=0;flip<2;flip++)for(let r=0;r<4;r++){
  let c=cells.map(([x,y])=>[flip?-x:x,y]);
  for(let i=0;i<r;i++)c=c.map(([x,y])=>[-y,x]);
  c=normalize(c);const key=JSON.stringify(c);if(!seen.has(key)){seen.add(key);out.push(c);}
 }
 return out;
}
