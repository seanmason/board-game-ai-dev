import assert from 'node:assert/strict';import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1200,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',e=>{if(e.type()==='error'&&!e.text().includes('favicon'))errors.push(e.text());});
const state=()=>page.evaluate(()=>{const d=JSON.parse(localStorage.getItem('board-game-ai-splendor-v1'));return d.history[d.index].state;});
try{
 await page.goto('http://127.0.0.1:8080/splendor/',{waitUntil:'networkidle'});
 assert.equal(await page.locator('h1').innerText(),'Splendor');assert.equal(await page.locator('#samples').count(),0);
 const fixture=await page.evaluate(async()=>{const {newGame}=await import('/splendor/core.js');return newGame({mode:'digital',seed:45});});
 for(let t=1;t<=3;t++)for(let i=0;i<4;i++)await page.locator(`#setup-${t}-${i}`).selectOption(String(fixture.market[t-1][i]));
 for(const id of fixture.nobles)await page.locator(`[name=noble][value="${id}"]`).check();
 await page.locator('[data-action=setup]').click();
 await page.waitForFunction(()=>Number(document.querySelector('#samples')?.textContent)>0);
 assert.equal((await state()).turn,0,'Search never commits moves');
 await page.screenshot({path:'/tmp/splendor-desktop.png',fullPage:true});
 await page.locator('[data-action=reserve]').first().click();
 assert.equal((await state()).phase,'reveal');assert.equal(await page.locator('#samples').count(),0);
 await page.reload({waitUntil:'networkidle'});assert.equal((await state()).phase,'reveal');
 const id=await page.locator('#reveal-card option').nth(1).getAttribute('value');
 await page.locator('#reveal-card').selectOption(id);await page.locator('[data-action=reveal]').click();
 assert.equal((await state()).turn,1);
 await page.locator('[data-action=undo]').click();assert.equal((await state()).phase,'reveal');
 await page.locator('[data-action=redo]').click();assert.equal((await state()).turn,1);
 await page.locator('[data-action=blind][data-tier="1"]').click();
 await page.locator('#reveal-card').selectOption('unknown');await page.locator('[data-action=reveal]').click();
 assert.equal((await state()).players[1].reserved[0].id,null);
 for(const i of [0,1,2])await page.locator('#take-'+i).fill('1');await page.locator('[data-action=take]').click();
 assert.equal((await state()).currentPlayer,1);assert.equal(await page.locator('#samples').count(),0);
 await page.locator('#identify-0').selectOption(await page.locator('#identify-0 option').nth(1).getAttribute('value'));
 await page.locator('[data-action=identify]').click();
 await page.waitForFunction(()=>Number(document.querySelector('#samples')?.textContent)>0);
 await page.locator('[data-action=pause]').click();await page.waitForTimeout(400);
 const paused=await page.locator('#samples').innerText();await page.waitForTimeout(500);assert.equal(await page.locator('#samples').innerText(),paused);
 await page.locator('[data-action=pause]').click();await page.waitForFunction(n=>Number(document.querySelector('#samples')?.textContent)>n,Number(paused));
 const before=await state();
 await page.locator('#import-file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({format:'board-game-ai-splendor',version:1,history:[{state:fixture,label:'Invalid position'}],index:.5}))});
 await page.getByRole('alert').filter({hasText:'Invalid session history position'}).waitFor();assert.deepEqual(await state(),before);
 await page.setViewportSize({width:390,height:844});assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+3),'Phone horizontal overflow');
 await page.screenshot({path:'/tmp/splendor-phone.png',fullPage:true});
 // A standalone build runs with all relative worker/shared dependencies.
 const standalone=await browser.newPage();standalone.on('pageerror',e=>errors.push(e.message));
 await standalone.goto('http://127.0.0.1:8080/standalone-splendor/',{waitUntil:'networkidle'});
 await standalone.locator('#mode').selectOption('digital');await standalone.locator('[data-action=new]').click();
 await standalone.waitForFunction(()=>Number(document.querySelector('#samples')?.textContent)>0);
 await standalone.locator('[data-action=suggestion]').first().click();
 const actual=await standalone.evaluate(()=>{const d=JSON.parse(localStorage.getItem('board-game-ai-splendor-v1'));return d.history[d.index].state;});
 assert.ok(actual.turn>0||['return','noble'].includes(actual.phase));
 await standalone.close();assert.deepEqual(errors,[]);
 console.log('Splendor browser passed: real setup, reveal persistence, unknown reservations, advice privacy, pause/resume, undo/redo, atomic import, phone layout and standalone worker.');
}finally{await page.screenshot({path:'/tmp/splendor-last.png',fullPage:true}).catch(()=>{});await browser.close();}
